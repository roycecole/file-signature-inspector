/* ---------------------------------------------------------------
   語言狀態與工具函式
   --------------------------------------------------------------- */
function detectInitialLang(){
  try{
    let saved = localStorage.getItem('fsi-lang');
    if(LANGS.indexOf(saved) >= 0) return saved;
  }catch(e){ /* 有些隱私模式會擋 localStorage，忽略即可 */ }
  let nav = ((navigator && navigator.language) || '').toLowerCase();
  // 簡體中文的地區/語言子標籤要先判斷，不然 "zh-cn" 這種也會被下面
  // 那條寬鬆的 "zh" 開頭判斷誤收成繁體。zh-tw／zh-hk／zh-mo／單純
  // "zh" 沒有明確子標籤時，維持這個工具原本的預設：當作繁體中文。
  if(/^zh-(cn|sg|hans)/.test(nav)) return 'zh-Hans';
  if(nav.indexOf('zh') === 0) return 'zh';
  if(nav.indexOf('ja') === 0) return 'ja';
  return 'en';
}

let currentLang = detectInitialLang();

// 查表 + 參數代換。找不到就退回英文，英文也沒有就回傳 key 本身
// （方便開發時一眼看出漏翻譯的地方）。
function t(key, params){
  let dict = I18N[currentLang] || {};
  let s = (key in dict) ? dict[key] : ((I18N.en && (key in I18N.en)) ? I18N.en[key] : key);
  if(params){
    Object.keys(params).forEach(function(k){
      s = s.split('{'+k+'}').join(params[k]);
    });
  }
  return s;
}

// 格式名稱翻譯：中文本身就是內部識別用的原始值，其他語言查
// FORMAT_NAME_I18N，查不到（多半是 PNG/JPEG 這類本來就是英文的名稱）
// 就直接顯示原始值。
function formatName(name){
  if(currentLang === 'zh' || !name) return name;
  let e = FORMAT_NAME_I18N[name];
  return (e && e[currentLang]) || name;
}

function kindLabel(type){
  return t('kind.' + type) || t('kind.other');
}

// 切換語言：存起來、更新 <html lang="">，然後呼叫 onLangChange()
// （由 app.js 定義，負責重新渲染畫面上所有文字）。
function setLang(lang){
  if(LANGS.indexOf(lang) < 0) return;
  currentLang = lang;
  try{ localStorage.setItem('fsi-lang', lang); }catch(e){}
  document.documentElement.setAttribute('lang', lang === 'zh' ? 'zh-Hant' : lang);
  if(typeof onLangChange === 'function') onLangChange();
}

// setLang() 的「安靜」版本：只換 currentLang，不碰 localStorage、不碰
// document、不觸發 onLangChange()。給 Web Worker 用——Worker 環境沒有
// document，呼叫一般的 setLang() 會直接拋例外；detect-worker.js
// 每次收到分析請求時，用這個把自己的 currentLang 對齊主執行緒目前
// 的語言（隨每個請求一起傳過來），這樣 Worker 裡產生的風險說明文字
// 才會是正確的語言，不會因為使用者中途切換語言而卡在舊的。
function setLangSilent(lang){
  if(LANGS.indexOf(lang) >= 0) currentLang = lang;
}

// 把畫面上「寫死在 HTML 裡」的靜態文字，套用目前語言。
// data-i18n="key"      → 用 textContent（純文字，無巨集標籤）
// data-i18n-html="key" → 用 innerHTML（內容含 <code>/<b> 這類標籤）
// data-i18n-placeholder="key" → 設定 input 的 placeholder
// data-i18n-aria-label="key"  → 設定 aria-label
// data-i18n-title="key"       → 設定滑鼠移上去看到的 title tooltip
function applyStaticI18n(root){
  let scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(function(el){
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-html]').forEach(function(el){
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  scope.querySelectorAll('[data-i18n-aria-label]').forEach(function(el){
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach(function(el){
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
}
