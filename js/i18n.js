/* =============================================================
   i18n.js — 多語系字典與翻譯工具函式
   ---------------------------------------------------------------
   支援 zh（繁體中文，原始語言）／en（English）／ja（日本語）。

   使用方式：
     t('some.key')                    → 查表，找不到就退回英文，再找不到就回傳 key 本身
     t('some.key', {name:'a.pdf'})    → 字典裡的 "{name}" 會被換成 'a.pdf'
     formatName('Word 文件 (OOXML)')  → 把 detectors.js/signatures.js 用的
                                          內部格式名稱轉成目前語言的顯示文字
     kindLabel('exec')                → 圖片/文件/純文字/執行檔/其他 的翻譯版

   語言判斷順序：使用者上次選過的（存在 localStorage）→ 瀏覽器語言
   （zh/ja 開頭才採用，其餘一律預設英文）→ 'en'。這個專案是純前端
   離線工具、不會蒐集任何資料，把語言偏好存在 localStorage 純粹是
   方便使用者下次打開時不用重選，跟「上傳資料」完全無關。

   新增一種語言：把 I18N 裡三個語言物件的 key 集合抄一份改語言就好，
   FORMAT_NAME_I18N 同理。這個檔案要在其他所有 JS 檔案「之前」載入，
   因為每個檔案的字串幾乎都透過 t() 產生。
   ============================================================= */

